#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");

const packageRoot = path.resolve(__dirname, "..");
const outFile = path.join(packageRoot, "src/core/devHost.generated.ts");

function getLanIp() {
  const nets = os.networkInterfaces();
  for (const entries of Object.values(nets)) {
    for (const net of entries ?? []) {
      if (net.family === "IPv4" && !net.internal) {
        return net.address;
      }
    }
  }
  return "127.0.0.1";
}

async function findBackendPort(host) {
  for (const port of [4001, 4000, 4002, 4003]) {
    try {
      const res = await fetch(`http://${host}:${port}/health`, {
        signal: AbortSignal.timeout(1500),
      });
      if (!res.ok) continue;
      const body = await res.json();
      if (body && typeof body === "object" && "database" in body) {
        return port;
      }
    } catch {
      // try next port
    }
  }
  return 4000;
}

async function main() {
  const host = getLanIp();
  const port = await findBackendPort("127.0.0.1");
  const contents = `/** Auto-generated by scripts/sync-dev-api-host.js — do not edit. */
export const DEV_LAN_HOST = ${JSON.stringify(host)};
export const DEV_BACKEND_PORT = ${port};
`;
  fs.writeFileSync(outFile, contents, "utf8");
  console.log(`[dev-api] LAN host ${host}, backend port ${port} → ${outFile}`);
}

main().catch((err) => {
  console.error("[dev-api] sync failed:", err.message);
  process.exit(1);
});
